import assert from 'node:assert/strict';
import {normaliseRecord,points,summarise,csv,markdown} from '../live/investigation_records.mjs';
const spec={x:'Drop height',xUnit:'m',y:'Rebound height',yUnit:'m',minX:0,minY:0};
const r=normaliseRecord({rows:[{x:'1',y:'.64',source:'mine',note:'first, "careful"'},{x:'1',y:'.60',source:'mine'},{x:'1',y:'.80',source:'supplied'},{x:'',y:'2'},{x:'3',y:'NaN'}],controlled:'Same ball',claim:'Energy spread into the floor.'});
assert.equal(points(r,spec).length,3);
assert.equal(summarise(r,spec)[0].mean,.62);
assert.equal(summarise(r,spec)[0].range,.040000000000000036);
assert.match(csv(r,spec),/Drop height \(m\)/);
assert.match(csv(r,spec),/"first, ""careful"""/);
assert.match(csv(normaliseRecord({rows:[{x:'1',y:'2',note:'=HYPERLINK("bad")'}]}),spec),/'=HYPERLINK/);
assert.match(markdown(r,spec),/My observation/);
assert.match(markdown(r,spec),/Supplied observation/);
assert.equal(normaliseRecord(null).rows.length,0);
assert.equal(normaliseRecord({rows:'wrong'}).rows.length,0);
assert.equal(normaliseRecord({claim:'x'.repeat(12000)}).claim.length,12000);
assert.equal(points(normaliseRecord({rows:[{x:'-1',y:'2'}]}),spec).length,0);
assert.deepEqual(normaliseRecord(JSON.parse(JSON.stringify(r))),r);
assert.equal(summarise(normaliseRecord({rows:[{x:'1',y:'2',source:'model',note:'Linear k20'},{x:'1',y:'3',source:'model',note:'Nonlinear k20'}]}),spec).length,2);
console.log('PASS investigation records: validation, empty/invalid values, labels, repeated values, exports, round trip');
