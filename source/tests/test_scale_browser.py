"""Focused public-UI regression checks. Run against an already served site."""
import sys, pathlib
from playwright.sync_api import sync_playwright, expect
URL=sys.argv[1] if len(sys.argv)>1 else 'http://localhost:8765/'
OUT=pathlib.Path(__file__).resolve().parents[1]/'build'/'scale-checks';OUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch()
    errors=[]
    for w in [320,390,820,1024,1180,1440]:
        page=browser.new_page(viewport={'width':w,'height':900},reduced_motion='reduce')
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(URL+'#explore-scale')
        page.get_by_role('button',name='Open Powers of Ten',exact=True).click()
        readout=page.locator('.scale-width')
        expect(readout).to_have_text('1 m across')
        page.get_by_role('button',name='10× larger',exact=True).click()
        expect(readout).to_have_text('10 m across')
        page.get_by_role('button',name='10× smaller',exact=True).click()
        expect(readout).to_have_text('1 m across')
        page.get_by_label('Jump to a landmark').select_option(label='Earth')
        before=readout.inner_text()
        page.get_by_role('button',name='Take a guided journey',exact=True).click()
        expect(readout).to_have_text(before)
        page.get_by_role('button',name='Begin at one metre',exact=True).click()
        expect(readout).to_have_text('1 m across')
        page.get_by_role('button',name='Next',exact=True).click()
        page.get_by_role('button',name='Make the view 10× wider',exact=True).click()
        expect(readout).to_have_text('10 m across')
        page.get_by_role('button',name='Next',exact=True).click()
        page.get_by_role('button',name='Visit one millimetre',exact=True).click()
        expect(readout).to_have_text('1 mm across')
        page.get_by_role('button',name='Close guide',exact=True).click()
        for theme in ['light','dark','sepia']:
            page.evaluate('(t)=>document.documentElement.dataset.theme=t',theme)
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),(w,theme,'overflow')
            page.get_by_role('button',name='Back to you',exact=True).click()
            page.get_by_role('button',name='10× larger',exact=True).click()
            page.locator('.scale-explorer').screenshot(path=str(OUT/f'{w}-{theme}.png'))
        for _ in range(3):
            page.get_by_role('button',name='Close explorer',exact=True).click()
            page.get_by_role('button',name='Open Powers of Ten',exact=True).click()
            expect(readout).to_have_text('1 m across')
        # Keyboard slider remains a real input, not a canvas-only control.
        slider=page.get_by_role('slider',name='View width, from proton scale to galaxy scale')
        slider.focus();slider.press('End');expect(slider).to_have_value('22')
        expect(page.get_by_role('button',name='10× larger',exact=True)).to_be_disabled()
        for _ in range(4): slider.press('ArrowLeft')
        expect(slider).to_have_value('21.8')
        expect(page.get_by_role('button',name='10× larger',exact=True)).to_be_disabled()
        slider.press('Home');expect(slider).to_have_value('-15')
        expect(page.get_by_role('button',name='10× smaller',exact=True)).to_be_disabled()
        for _ in range(4): slider.press('ArrowRight')
        expect(slider).to_have_value('-14.8')
        expect(page.get_by_role('button',name='10× smaller',exact=True)).to_be_disabled()
        page.close();print('PASS viewport',w)
    assert not errors,errors
    context=browser.new_context(service_workers='allow')
    page=context.new_page();page.goto(URL+'#explore-scale');page.evaluate('navigator.serviceWorker.ready')
    page.get_by_role('button',name='Open Powers of Ten',exact=True).click()
    page.wait_for_function("Array.from(document.images).every(i=>i.complete)")
    context.set_offline(True);page.reload()
    page.get_by_role('button',name='Open Powers of Ten',exact=True).click()
    expect(page.locator('.scale-width')).to_have_text('1 m across')
    assert page.evaluate("Array.from(document.images).every(i=>i.complete && i.naturalWidth>0)")
    print('PASS offline reload')
    context.set_offline(False)
    moving=browser.new_page(reduced_motion='no-preference')
    moving.goto(URL+'#explore-scale')
    moving.get_by_role('button',name='Open Powers of Ten',exact=True).click()
    for _ in range(3): moving.get_by_role('button',name='10× larger',exact=True).click()
    expect(moving.locator('.scale-width')).to_have_text('1 km across')
    moving.get_by_role('button',name='10× smaller',exact=True).click()
    expect(moving.locator('.scale-width')).to_have_text('100 m across')
    print('PASS interrupted animation / rapid presses')
    browser.close()
